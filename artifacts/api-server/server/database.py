import os
import re
from contextlib import contextmanager
from decimal import Decimal
from urllib.parse import unquote, urlparse

import oracledb
import psycopg2
import psycopg2.extras
import pymysql
import pymysql.cursors

DATABASE_URL = os.environ.get("DATABASE_URL")
if not DATABASE_URL:
    raise RuntimeError("DATABASE_URL must be set.")

IS_MYSQL = DATABASE_URL.startswith(("mysql://", "mysql2://"))
IS_ORACLE = DATABASE_URL.startswith(("oracle://", "oracle+oracledb://"))
IS_POSTGRES = not IS_MYSQL and not IS_ORACLE


def get_connection():
    if IS_ORACLE:
        user = os.environ.get("ORACLE_USER")
        password = os.environ.get("ORACLE_PASSWORD")
        dsn = os.environ.get("ORACLE_DSN")
        wallet_location = os.environ.get("ORACLE_WALLET_LOCATION")
        wallet_password = os.environ.get("ORACLE_WALLET_PASSWORD")
        if not all((user, password, dsn, wallet_location, wallet_password)):
            raise RuntimeError(
                "Oracle connections require ORACLE_USER, ORACLE_PASSWORD, "
                "ORACLE_DSN, ORACLE_WALLET_LOCATION, and ORACLE_WALLET_PASSWORD."
            )
        if not os.path.isfile(os.path.join(wallet_location, "tnsnames.ora")):
            raise RuntimeError(
                "ORACLE_WALLET_LOCATION must contain the wallet's tnsnames.ora file."
            )
        return oracledb.connect(
            user=user,
            password=password,
            dsn=dsn,
            config_dir=wallet_location,
            wallet_location=wallet_location,
            wallet_password=wallet_password,
        )
    if IS_MYSQL:
        parsed = urlparse(DATABASE_URL)
        return pymysql.connect(
            host=parsed.hostname or "localhost",
            port=parsed.port or 3306,
            user=unquote(parsed.username or ""),
            password=unquote(parsed.password or ""),
            database=unquote(parsed.path.lstrip("/")),
            charset="utf8mb4",
            cursorclass=pymysql.cursors.DictCursor,
        )
    if DATABASE_URL.startswith(("postgres://", "postgresql://")):
        return psycopg2.connect(
            DATABASE_URL, cursor_factory=psycopg2.extras.RealDictCursor
        )
    raise RuntimeError(
        "DATABASE_URL must use mysql://, postgresql://, or oracle://."
    )


def _oracle_sql(statement: str) -> str:
    """Translate the small shared SQL subset used by the API to Oracle SQL."""
    bind_index = 0

    def replace_bind(_match):
        nonlocal bind_index
        bind_index += 1
        return f":p{bind_index - 1}"

    statement = re.sub(r"%s", replace_bind, statement)
    statement = re.sub(r"\bNOW\(\)", "CURRENT_TIMESTAMP", statement, flags=re.IGNORECASE)
    limit = re.search(r"\s+LIMIT\s+(\d+)\s*;?\s*$", statement, flags=re.IGNORECASE)
    if limit:
        statement = (
            statement[: limit.start()]
            + f" FETCH FIRST {limit.group(1)} ROWS ONLY"
        )
    return statement


def _oracle_bind_values(params):
    if params is None:
        return {}
    if isinstance(params, dict):
        values = params
    else:
        values = {f"p{index}": value for index, value in enumerate(params)}
    return {
        key: ("Y" if value else "N") if isinstance(value, bool) else value
        for key, value in values.items()
    }


def _oracle_ddl(ddl: str) -> str:
    ddl = ddl.replace("CREATE TABLE IF NOT EXISTS", "CREATE TABLE")
    ddl = re.sub(
        r"\bSERIAL PRIMARY KEY\b",
        "NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY",
        ddl,
    )
    ddl = re.sub(r"\bTEXT\b", "VARCHAR2(4000)", ddl)
    ddl = re.sub(
        r"\b(scripture_text|body|summary|content|answer)\s+VARCHAR2\(4000\)",
        r"\1 CLOB",
        ddl,
        flags=re.IGNORECASE,
    )
    ddl = re.sub(r"\bBOOLEAN\b", "CHAR(1)", ddl, flags=re.IGNORECASE)
    ddl = re.sub(r"DEFAULT\s+TRUE\b", "DEFAULT 'Y'", ddl, flags=re.IGNORECASE)
    return re.sub(
        r"DEFAULT\s+NOW\(\)",
        "DEFAULT CURRENT_TIMESTAMP",
        ddl,
        flags=re.IGNORECASE,
    )


def table_names():
    with db_cursor() as cur:
        if IS_ORACLE:
            cur.execute("SELECT table_name FROM user_tables")
        elif IS_MYSQL:
            cur.execute(
                """SELECT table_name FROM information_schema.tables
                   WHERE table_schema = DATABASE()"""
            )
        else:
            cur.execute(
                "SELECT tablename AS table_name FROM pg_tables WHERE schemaname = 'public'"
            )
        return {row["table_name"].lower() for row in cur.fetchall()}


class OracleCursor:
    def __init__(self, cursor):
        self._cursor = cursor

    def execute(self, statement, params=None):
        statement = _oracle_sql(statement)
        if params is None:
            self._cursor.execute(statement)
        else:
            self._cursor.execute(statement, _oracle_bind_values(params))
        return self

    def fetchone(self):
        row = self._cursor.fetchone()
        return self._mapping(row) if row is not None else None

    def fetchall(self):
        return [self._mapping(row) for row in self._cursor.fetchall()]

    @property
    def rowcount(self):
        return self._cursor.rowcount

    def close(self):
        self._cursor.close()

    def _mapping(self, row):
        names = [column[0].lower() for column in self._cursor.description]
        result = {}
        for name, value in zip(names, row):
            if hasattr(value, "read"):
                value = value.read()
            elif isinstance(value, Decimal) and value == value.to_integral_value():
                value = int(value)
            if name in {"completed", "is_anonymous"} and value is not None:
                value = value in (True, "Y", "y", 1)
            result[name] = value
        return result

    def insert_returning(self, table, statement, params):
        values = _oracle_bind_values(params)
        output_id = self._cursor.var(oracledb.NUMBER)
        sql = _oracle_sql(statement.rstrip().rstrip(";"))
        self._cursor.execute(
            f"{sql} RETURNING id INTO :inserted_id",
            {**values, "inserted_id": output_id},
        )
        inserted_id = output_id.getvalue()
        if isinstance(inserted_id, list):
            inserted_id = inserted_id[0]
        self.execute(f"SELECT * FROM {table} WHERE id = %s", (inserted_id,))
        return self.fetchone()


@contextmanager
def db_cursor(commit: bool = False):
    conn = get_connection()
    cur = None
    try:
        cur = conn.cursor()
        if IS_ORACLE:
            cur = OracleCursor(cur)
        yield cur
        if commit:
            conn.commit()
    except Exception:
        conn.rollback()
        raise
    finally:
        try:
            if cur is not None:
                cur.close()
        finally:
            conn.close()


def insert_returning(cur, table: str, statement: str, params: tuple):
    if IS_ORACLE:
        return cur.insert_returning(table, statement, params)
    if IS_MYSQL:
        cur.execute(statement, params)
        cur.execute(f"SELECT * FROM {table} WHERE id = %s", (cur.lastrowid,))
    else:
        cur.execute(f"{statement.rstrip().rstrip(';')} RETURNING *", params)
    return cur.fetchone()


def update_returning(cur, table: str, statement: str, params: tuple, row_id: int):
    if IS_ORACLE:
        cur.execute(statement, params)
        cur.execute(f"SELECT * FROM {table} WHERE id = %s", (row_id,))
        return cur.fetchone()
    if IS_MYSQL:
        cur.execute(statement, params)
        cur.execute(f"SELECT * FROM {table} WHERE id = %s", (row_id,))
    else:
        cur.execute(f"{statement.rstrip().rstrip(';')} RETURNING *", params)
    return cur.fetchone()


def create_tables():
    """Ensure all application tables exist without removing existing data."""
    ddl = """
    CREATE TABLE IF NOT EXISTS users (
        id SERIAL PRIMARY KEY,
        first_name TEXT NOT NULL,
        last_name TEXT NOT NULL,
        username TEXT NOT NULL UNIQUE,
        email TEXT NOT NULL UNIQUE,
        password_hash TEXT NOT NULL,
        clerk_id VARCHAR(255) UNIQUE,
        bio TEXT DEFAULT '',
        created_at TIMESTAMP DEFAULT NOW() NOT NULL
    );

    CREATE TABLE IF NOT EXISTS devotionals (
        id SERIAL PRIMARY KEY,
        title TEXT NOT NULL,
        scripture_ref TEXT NOT NULL,
        scripture_text TEXT NOT NULL,
        body TEXT NOT NULL,
        publish_date TIMESTAMP DEFAULT NOW() NOT NULL,
        created_at TIMESTAMP DEFAULT NOW() NOT NULL
    );

    CREATE TABLE IF NOT EXISTS reading_plans (
        id SERIAL PRIMARY KEY,
        title TEXT NOT NULL,
        description TEXT DEFAULT '',
        start_date DATE,
        created_at TIMESTAMP DEFAULT NOW() NOT NULL
    );

    CREATE TABLE IF NOT EXISTS reading_plan_days (
        id SERIAL PRIMARY KEY,
        plan_id INTEGER NOT NULL,
        day_number INTEGER NOT NULL,
        passage TEXT NOT NULL,
        reflection TEXT DEFAULT ''
    );

    CREATE TABLE IF NOT EXISTS reading_progress (
        id SERIAL PRIMARY KEY,
        user_id INTEGER NOT NULL,
        plan_day_id INTEGER NOT NULL,
        completed BOOLEAN DEFAULT TRUE NOT NULL,
        completed_at TIMESTAMP DEFAULT NOW() NOT NULL
    );

    CREATE TABLE IF NOT EXISTS reading_summaries (
        id SERIAL PRIMARY KEY,
        plan_day_id INTEGER NOT NULL UNIQUE,
        summary TEXT NOT NULL,
        created_at TIMESTAMP DEFAULT NOW() NOT NULL
    );

    CREATE TABLE IF NOT EXISTS prayer_requests (
        id SERIAL PRIMARY KEY,
        user_id INTEGER NOT NULL,
        content TEXT NOT NULL,
        is_anonymous BOOLEAN DEFAULT TRUE NOT NULL,
        pray_count INTEGER DEFAULT 0 NOT NULL,
        created_at TIMESTAMP DEFAULT NOW() NOT NULL
    );

    CREATE TABLE IF NOT EXISTS prayer_prays (
        id SERIAL PRIMARY KEY,
        prayer_request_id INTEGER NOT NULL,
        user_id INTEGER NOT NULL,
        created_at TIMESTAMP DEFAULT NOW() NOT NULL
    );

    CREATE TABLE IF NOT EXISTS events (
        id SERIAL PRIMARY KEY,
        title TEXT NOT NULL,
        description TEXT DEFAULT '',
        location TEXT DEFAULT '',
        starts_at TIMESTAMP NOT NULL,
        created_at TIMESTAMP DEFAULT NOW() NOT NULL
    );

    CREATE TABLE IF NOT EXISTS event_rsvps (
        id SERIAL PRIMARY KEY,
        event_id INTEGER NOT NULL,
        user_id INTEGER NOT NULL,
        created_at TIMESTAMP DEFAULT NOW() NOT NULL
    );

    CREATE TABLE IF NOT EXISTS chat_messages (
        id SERIAL PRIMARY KEY,
        room TEXT NOT NULL,
        user_id INTEGER NOT NULL,
        display_name TEXT NOT NULL,
        content TEXT NOT NULL,
        reply_to_id INTEGER,
        created_at TIMESTAMP DEFAULT NOW() NOT NULL
    );

    CREATE TABLE IF NOT EXISTS questions (
        id SERIAL PRIMARY KEY,
        user_id INTEGER NOT NULL,
        ticket_code TEXT NOT NULL,
        content TEXT NOT NULL,
        answer TEXT,
        created_at TIMESTAMP DEFAULT NOW() NOT NULL,
        answered_at TIMESTAMP NULL
    );

    CREATE TABLE IF NOT EXISTS music_tracks (
        id SERIAL PRIMARY KEY,
        title TEXT NOT NULL,
        artist TEXT NOT NULL,
        duration INTEGER NOT NULL DEFAULT 0,
        audio_path TEXT NOT NULL,
        created_at TIMESTAMP DEFAULT NOW() NOT NULL
    );
    """
    if IS_ORACLE:
        ddl = _oracle_ddl(ddl)
    elif IS_MYSQL:
        ddl = ddl.replace(
            "SERIAL PRIMARY KEY", "INTEGER PRIMARY KEY AUTO_INCREMENT"
        ).replace("DEFAULT NOW()", "DEFAULT CURRENT_TIMESTAMP")

    with db_cursor(commit=True) as cur:
        for statement in ddl.split(";"):
            if statement.strip():
                if IS_ORACLE:
                    try:
                        cur.execute(statement)
                    except oracledb.DatabaseError as exc:
                        error = exc.args[0] if exc.args else None
                        if getattr(error, "code", None) != 955:
                            raise
                else:
                    cur.execute(statement)

        if IS_ORACLE:
            columns = (
                ("users", "clerk_id", "VARCHAR2(255) UNIQUE"),
                ("reading_plans", "start_date", "DATE"),
                ("users", "avatar_path", "VARCHAR2(4000)"),
                ("chat_messages", "reply_to_id", "INTEGER"),
            )
            for table, column, definition in columns:
                cur.execute(
                    """SELECT COUNT(*) AS column_count FROM user_tab_columns
                       WHERE table_name = %s AND column_name = %s""",
                    (table.upper(), column.upper()),
                )
                if not cur.fetchone()["column_count"]:
                    cur.execute(
                        f"ALTER TABLE {table} ADD ({column} {definition})"
                    )
        elif IS_MYSQL:
            cur.execute("SHOW COLUMNS FROM users LIKE 'clerk_id'")
            if not cur.fetchone():
                cur.execute(
                    "ALTER TABLE users ADD COLUMN clerk_id VARCHAR(255) NULL UNIQUE"
                )
            cur.execute("SHOW COLUMNS FROM reading_plans LIKE 'start_date'")
            if not cur.fetchone():
                cur.execute("ALTER TABLE reading_plans ADD COLUMN start_date DATE NULL")
            cur.execute("SHOW COLUMNS FROM users LIKE 'avatar_path'")
            if not cur.fetchone():
                cur.execute(
                    "ALTER TABLE users ADD COLUMN avatar_path TEXT DEFAULT ''"
                )
            cur.execute("SHOW COLUMNS FROM chat_messages LIKE 'reply_to_id'")
            if not cur.fetchone():
                cur.execute("ALTER TABLE chat_messages ADD COLUMN reply_to_id INTEGER NULL")
        else:
            cur.execute(
                "ALTER TABLE users ADD COLUMN IF NOT EXISTS clerk_id VARCHAR(255) UNIQUE"
            )
            cur.execute(
                "ALTER TABLE reading_plans ADD COLUMN IF NOT EXISTS start_date DATE"
            )
            cur.execute(
                "ALTER TABLE users ADD COLUMN IF NOT EXISTS avatar_path TEXT DEFAULT ''"
            )
            cur.execute(
                "ALTER TABLE chat_messages ADD COLUMN IF NOT EXISTS reply_to_id INTEGER"
            )
